"""Shared arithmetic and the internal replay used to score fresh candidates.

The public verifier (``src/verify.py``) remains the independent legality gate
for exported submissions; this replay is the in-process check that a candidate
generated by the solver is legal before it is accepted.  It contains no search
policy.
"""

import json


def arithmetic(op, a, b):
    """Apply one Santa instruction; raise on illegal operations."""
    if op == '+':
        return a + b
    if op == '-':
        return a - b
    if op == '*':
        return a * b
    if op == '/' and b and a % b == 0:
        return a // b
    raise ValueError('illegal operation')


def replay(row, program):
    """Replay ``program`` on one puzzle row and return its instruction count."""
    start = json.loads(row['starting_values'])
    targets = set(json.loads(row['targets']))
    limit = int(row['value_limit'])
    n = int(row['registers'])
    if len(program) > 4096 or len(json.dumps(program, separators=(',', ':')).encode()) > 128 * 1024:
        raise ValueError('program size limit')
    regs = start + [None] * (n - len(start))
    seen = set(start)
    for op, a, b, d in program:
        if not all(type(i) is int and 0 <= i < n for i in (a, b, d)):
            raise ValueError('register index')
        x, y = regs[a], regs[b]
        if x is None or y is None:
            raise ValueError('uninitialized register')
        if op == '+':
            z = x + y
        elif op == '-':
            z = x - y
        elif op == '*':
            z = x * y
        elif op == '/' and y and x % y == 0:
            z = x // y
        else:
            raise ValueError('invalid operator or division')
        if not 0 < z <= limit:
            raise ValueError('value limit')
        regs[d] = z
        seen.add(z)
    if not targets <= seen:
        raise ValueError('missing targets')
    return len(program)
