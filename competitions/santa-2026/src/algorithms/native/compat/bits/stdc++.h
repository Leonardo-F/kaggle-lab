// Compatibility shim for compilers that ship no libstdc++ <bits/stdc++.h>.
//
// The two frozen V9 constructor kernels are kept byte-identical to the research
// handoff (GCC/libstdc++ C++17).  Apple Clang uses libc++ and has no aggregate
// standard header, so native/build.py adds this directory to the include path
// only when a compiler probe shows the real header is missing.  The shim only
// forwards to individual standard headers; it changes no algorithm behaviour.
